package com.ibigroup.mobile.otp.android.json;

public class AgencyNameMapping {
    private String agencyName;
    private String mappedAgencyName;

    public String getAgencyName() {
        return agencyName;
    }

    public void setAgencyName(String agencyName) {
        this.agencyName = agencyName;
    }

    public String getMappedAgencyName() {
        return mappedAgencyName;
    }

    public void setMappedAgencyName(String mappedAgencyName) {
        this.mappedAgencyName = mappedAgencyName;
    }
}
